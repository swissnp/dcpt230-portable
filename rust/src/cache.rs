fn canonical_tail(tail:&mut [u8])->Option<u64> {
    let marker=b"\ntrailer << ";
    let begin=tail.windows(marker.len()).rposition(|s|s==marker)?+marker.len();
    let end=begin+tail[begin..].windows(3).position(|s|s==b">>\n")?;
    let suffix=std::str::from_utf8(&tail[end+3..]).ok()?;
    let lines=suffix.split_whitespace().collect::<Vec<_>>();
    if lines.len()!=3 || lines[0]!="startxref" || lines[2]!="%%EOF" {return None}
    let xref=lines[1].parse().ok()?;
    let id=b"/ID [<";
    let at=begin+tail[begin..end].windows(id.len()).position(|s|s==id)?;
    // Only accept the simple non-encrypted dictionary emitted by qpdf/pdftopdf.
    let before=std::str::from_utf8(&tail[begin..at]).ok()?;
    for word in before.split_whitespace() {
        if !["/Info","/Root","/Size","R"].contains(&word) && !word.bytes().all(|b|b.is_ascii_digit()) {
            return None;
        }
    }
    let first=at+id.len();let second=first+34;
    if second+34>end || &tail[first+32..second]!=b"><" ||
        &tail[second+32..second+34]!=b">]" ||
        !tail[second+34..end].iter().all(u8::is_ascii_whitespace) ||
        !tail[first..first+32].iter().all(u8::is_ascii_hexdigit) ||
        !tail[second..second+32].iter().all(u8::is_ascii_hexdigit) {return None}
    tail[first..first+32].fill(b'0');tail[second..second+32].fill(b'0');
    Some(xref)
}
fn input_digest(input:&PathBuf)->Result<String> {
    let mut file=File::open(input)?;let size=file.metadata()?.len();
    // Keep memory bounded: inspect only header and tail, stream everything between.
    let head_len=size.min(512) as usize;
    let mut head=vec![0;head_len];file.read_exact(&mut head)?;
    if size<=head_len as u64 || !canonical_header(&mut head) {return digest(input)}
    let tail_len=(size-head_len as u64).min(8192) as usize;
    file.seek(SeekFrom::End(-(tail_len as i64)))?;
    let mut tail=vec![0;tail_len];file.read_exact(&mut tail)?;
    let xref=match canonical_tail(&mut tail){Some(n)=>n,None=>return digest(input)};
    if xref>=size {return digest(input)}
    file.seek(SeekFrom::Start(xref))?;let mut magic=[0;5];file.read_exact(&mut magic)?;
    if &magic!=b"xref\n" {return digest(input)}
    let mut child=Command::new("sha256sum").stdin(Stdio::piped()).stdout(Stdio::piped()).spawn()?;
    let result=(||->Result<()>{
        let mut pipe=child.stdin.take().ok_or("Missing SHA256 input")?;
        pipe.write_all(&head)?;file.seek(SeekFrom::Start(head_len as u64))?;
        io::copy(&mut file.take(size-head_len as u64-tail_len as u64),&mut pipe)?;
        pipe.write_all(&tail)?;Ok(())
    })();
    if let Err(e)=result {let _=child.kill();let _=child.wait();return Err(e)}
    let output=child.wait_with_output()?;
    if !output.status.success(){return Err("SHA256 input failed".into())}
    hash_text(output.stdout)
}
impl Cache {
    pub fn prepare(opts:&HashMap<String,String>,input:&PathBuf,temp:&PathBuf)->Result<Option<Self>> {
        match value(opts,"BRCache","Off") {
            "Off"=>return Ok(None), "On"=>(), _=>return Err("Unsupported cache option".into())
        }
        let result=(||->Result<Self>{
            let dir=PathBuf::from(std::env::var("DCPT230_CACHE_DIR")
                .map_err(|_|"BRCache=On requires DCPT230_CACHE_DIR")?);
            if !dir.is_absolute() { return Err("Cache directory must be absolute".into()); }
            let mut builder=fs::DirBuilder::new();
            #[cfg(unix)] builder.mode(0o700);
            match builder.create(&dir) {
                Ok(())=>(),Err(e) if e.kind()==io::ErrorKind::AlreadyExists=>(),Err(e)=>return Err(e.into())
            }
            let m=fs::symlink_metadata(&dir)?;
            if !m.is_dir() { return Err("Cache must be a real directory".into()); }
            #[cfg(unix)]
            if m.uid()!=fs::metadata(temp)?.uid() || m.mode()&0o077!=0 {
                return Err("Cache directory must be owned by filter user and mode 0700".into());
            }
            let version=Command::new("gs").arg("--version").output()?;
            if !version.status.success() { return Err("Ghostscript version failed".into()); }
            let metadata=temp.join("cache-key");
            fs::write(&metadata,format!("dcpt230-rust-0.4.0\n{}\n{}\n{}\n{}",
                input_digest(input)?,value(opts,"PageSize","A4"),value(opts,"BRMonoColor","FullColor"),
                String::from_utf8(version.stdout)?))?;
            Ok(Self{dir,key:digest(&metadata)?})
        })();
        match result {
            Ok(c)=>Ok(Some(c)),
            Err(e)=>{eprintln!("WARNING: Render cache disabled: {e}");Ok(None)}
        }
    }
    fn path(&self)->PathBuf { self.dir.join(format!("{}.raster",self.key)) }
    pub fn load(&self)->Result<Option<(File,usize)>> {
        let path=self.path();
        let m=match fs::symlink_metadata(&path) {Ok(m)=>m,Err(_)=>return Ok(None)};
        if !m.is_file() || m.len()>MAX_ENTRY || SystemTime::now().duration_since(m.modified()?).unwrap_or_default()>TTL {
            return Ok(None);
        }
        let mut open=OpenOptions::new();open.read(true);
        // Linux PowerPC assigns O_NOFOLLOW a different bit from asm-generic.
        #[cfg(all(target_os="linux", target_arch="powerpc64"))]
        open.custom_flags(0x8000);
        #[cfg(all(target_os="linux", not(target_arch="powerpc64")))]
        open.custom_flags(0x20000); // O_NOFOLLOW
        let mut f=open.open(path)?;
        let mut prefix=[0u8;24];f.read_exact(&mut prefix)?;
        if &prefix[..8]!=b"T230C004" {return Ok(None)}
        let pages=u64::from_be_bytes(prefix[8..16].try_into()?);
        let length=u64::from_be_bytes(prefix[16..24].try_into()?);
        if pages==0 || pages>10000 || length+24!=m.len() {return Ok(None)}
        // SHA256 sidecar detects truncation/corruption before any output is delivered.
        let expected=fs::read_to_string(self.dir.join(format!("{}.sha256",self.key)))?;
        if digest(&self.path())?!=expected {return Ok(None)}
        Ok(Some((f,pages as usize)))
    }
    pub fn store(&self,raster:&mut File,pages:usize,temp:&PathBuf)->Result<()> {
        // Serialize eviction and commits; concurrent jobs still render independently.
        let lockpath=self.dir.join(".write-lock");
        let lock=match OpenOptions::new().write(true).create_new(true).open(&lockpath) {
            Ok(f)=>f,Err(e) if e.kind()==io::ErrorKind::AlreadyExists=>return Ok(()),Err(e)=>return Err(e.into())
        };
        struct Lock(PathBuf);
        impl Drop for Lock {fn drop(&mut self){let _=fs::remove_file(&self.0);}}
        let _lock=Lock(lockpath);drop(lock);
        let length=raster.metadata()?.len();
        if length+24>MAX_ENTRY {return Ok(())}
        // Remove expired entries, then oldest entries to enforce the disk budget.
        let mut entries=Vec::new();
        for entry in fs::read_dir(&self.dir)? {
            let p=entry?.path();
            if p.extension().and_then(|s|s.to_str())!=Some("raster") {continue}
            let m=fs::symlink_metadata(&p)?;
            if !m.is_file() {continue}
            let date=m.modified()?;
            if SystemTime::now().duration_since(date).unwrap_or_default()>TTL {
                let _=fs::remove_file(p.with_extension("sha256"));let _=fs::remove_file(p);
            } else {entries.push((date,m.len(),p))}
        }
        entries.sort_by_key(|e|e.0);
        let mut total:u64=entries.iter().map(|e|e.1+64).sum();
        let mut count=entries.len();
        for (_,size,p) in entries {
            if total+length+88<=MAX_TOTAL && count<128 {break}
            let _=fs::remove_file(p.with_extension("sha256"));fs::remove_file(p)?;total-=size+64;count-=1;
        }
        // Stage in the cache directory so rename stays atomic across filesystems.
        let unique=temp.file_name().ok_or("Missing temporary name")?;
        let staging=self.dir.join(unique);
        let result=(||->Result<()> {
            let mut open=OpenOptions::new();open.write(true).create_new(true);
            #[cfg(unix)] open.mode(0o600);
            let mut f=open.open(&staging)?;
            f.write_all(b"T230C004")?;f.write_all(&(pages as u64).to_be_bytes())?;
            f.write_all(&length.to_be_bytes())?;
            raster.seek(SeekFrom::Start(0))?;io::copy(raster,&mut f)?;f.sync_all()?;drop(f);
            let hash=digest(&staging)?;
            let side=staging.with_extension("sha256");fs::write(&side,hash)?;
            fs::rename(&staging,self.path())?;
            fs::rename(&side,self.dir.join(format!("{}.sha256",self.key)))?;
            Ok(())
        })();
        let _=fs::remove_file(&staging);let _=fs::remove_file(staging.with_extension("sha256"));
        result
    }
}
