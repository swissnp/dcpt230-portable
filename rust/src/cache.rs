//! Opt-in private disk cache. Cache only raster, never titles/copies/PJL.
use super::*;
use std::time::{SystemTime, Duration};
#[cfg(unix)]
use std::os::unix::fs::{MetadataExt, OpenOptionsExt};
const MAX_ENTRY:u64=64*1024*1024;
const MAX_TOTAL:u64=256*1024*1024;
const TTL:Duration=Duration::from_secs(24*3600);
pub struct Cache { dir:PathBuf, key:String }
fn hash_text(data:Vec<u8>)->Result<String> {
    let text=String::from_utf8(data)?;
    let hash=text.split_whitespace().next().ok_or("Missing SHA256")?;
    if hash.len()!=64 || !hash.bytes().all(|b| b.is_ascii_hexdigit()) { return Err("Invalid SHA256".into()); }
    Ok(hash.to_owned())
}
fn digest(file:&PathBuf) -> Result<String> {
    let output=Command::new("sha256sum").arg(file).output()?;
    if !output.status.success() { return Err("sha256sum failed".into()); }
    hash_text(output.stdout)
}
fn canonical_header(head:&mut [u8])->bool {
    if !head.starts_with(b"%PDF-") {return false}
    let lines=head.split(|b|*b==b'\n').take_while(|line|line.starts_with(b"%")).map(|l|l.to_vec()).collect::<Vec<_>>();
    if !lines.iter().any(|l|l==b"% This file was generated by pdftopdf") {return false}
    let mut offset=0;
    for line in lines {
        if line.starts_with(b"%%PDFTOPDFNumCopies : ") {
            let start=offset+b"%%PDFTOPDFNumCopies : ".len();
            let end=offset+line.len();
            if start<end && head[start..end].iter().all(u8::is_ascii_digit) {
                head[start..end].fill(b'0');
            }
        }
        offset+=line.len()+1;
    }
    true
}

